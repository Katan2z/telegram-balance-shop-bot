const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const source=fs.readFileSync('docs/control/planner-ui.js','utf8');
const wrapper=source.slice(source.indexOf('  if(window.openPage)'),source.indexOf('  window.addEventListener'));
const calls=[],crumb={},buttons=[{dataset:{page:'schedule'},classList:{toggle(){}}},{dataset:{page:'schedule-builder'},classList:{toggle(){}}}];
const context={window:{openPage:page=>calls.push(page)},state:null,worker:null,job:0,confirm:()=>true,mount:()=>calls.push('mount-builder'),document:{querySelector:selector=>selector==='#crumb'?crumb:{},querySelectorAll:()=>buttons},location:{hash:''}};
vm.runInNewContext(wrapper,context);
context.window.openPage('schedule');assert.deepEqual(calls,['schedule'],'availability route stays in the existing schedule section');
context.window.openPage('schedule-builder');assert.equal(calls.at(-1),'mount-builder');assert.equal(crumb.textContent,'Составить расписание');
assert.ok(fs.readFileSync('docs/control/app.js','utf8').includes("['schedule-builder','▦','Составить расписание']"));
const legacy=fs.readFileSync('docs/control/live-sections.js','utf8');
const renderer=legacy.slice(legacy.indexOf('  function renderScheduleEditor('),legacy.indexOf('  function editShopItem('));
const root={innerHTML:'',querySelector:()=>({}),querySelectorAll:()=>[]};
const c={esc:value=>String(value??''),date:value=>value,window:{},toast(){}};
vm.runInNewContext(renderer+';globalThis.render=renderScheduleEditor;',c);
const rows={entries:[{employee_profile_id:1,employee_name:'Example',availability:{mon:'09:00–17:00',tue:'ФТ'},final_schedule:{mon:'10:00–16:00'}}]};
c.render(root,'2026-10-19',rows);
assert.ok(root.innerHTML.includes('data-day="mon" value="09:00–17:00"'));
assert.ok(root.innerHTML.includes('data-day="tue" value="ФТ"'));
assert.ok(root.innerHTML.includes('readonly'),'source availability is not edited as an assigned shift');
c.render(root,'2026-10-19',rows,'final');
assert.ok(root.innerHTML.includes('data-day="mon" value="10:00–16:00"'));
assert.ok(root.innerHTML.includes('data-day="tue" value=""'),'missing final shifts must not fall back to availability');
console.log('Separate schedule and builder route tests passed');
