const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const P=require('../docs/control/planner-engine.js');
const source=fs.readFileSync('docs/control/planner-ui.js','utf8');
const helpers=source.slice(source.indexOf('  function readableIssue('),source.indexOf('  function report()'));
const config=P.defaults();config.reviewed=true;config.spmh=150;
P.DAYS.forEach(day=>config.forecasts[day]={revenue:10000,checks:600,averageCheck:null});
const state={config,employees:[{employee_profile_id:42,employee_name:'Example',availability:{mon:'ФТ'}}],shifts:[],stale:false};
const context={P,state,labels:['ПН','ВТ','СР','ЧТ','ПТ','СБ','ВС'],dayDate:index=>String(index+1),field:(path,value)=>`<input data-config="${path}" value="${value}">`,weatherMarkup:()=>'<p>No weather</p>',escape:value=>String(value??'').replaceAll('<','&lt;').replaceAll('>','&gt;')};
vm.runInNewContext(helpers+';globalThis.inputs=inputsMarkup;globalThis.review=reviewMarkup;globalThis.issue=readableIssue;',context);
const html=context.inputs();
assert.ok(html.includes('id="plannerKeeper"'), 'supported r_keeper export can be selected');
assert.ok(html.includes('Продажи прошлой недели не считаются прогнозом автоматически'));
assert.ok(html.includes('500 чеков'));
assert.equal((html.match(/data-config="forecasts\./g)||[]).length,21);
assert.ok(html.includes('Учтён')||html.includes('учтён')||html.includes('включили'), 'double-counting explanation stays visible');
assert.equal(context.issue('42/mon: смена вне доступности'),'Example, ПН: смена вне доступности');
assert.ok(context.review().includes('Расписание пока пустое'));
assert.ok(context.review().includes('disabled'), 'empty schedule cannot be published through the review screen');
state.stale=true;
assert.ok(context.review().includes('возможности')||context.review().includes('Возможности'));
config.events=[{day:'mon',title:'<script>',start:600,end:720,percent:10,laborPercent:0,included:true}];
assert.ok(!context.inputs().includes('<script>'), 'event titles are escaped');
state.preview=true;
context.rosterMarkup=available=>{assert.equal(available,true);return '<table>Employee availability</table>';};
vm.runInNewContext('globalThis.simple=simpleMarkup;',context);
assert.ok(context.simple().includes('ЭТО ОБРАЗЕЦ'), 'demo must never be confused with real employee data');
assert.ok(context.simple().includes('Составить расписание автоматически'));
assert.ok(context.simple().includes('Employee availability'), 'availability is on the main screen');
vm.runInNewContext('globalThis.card=staffCardMarkup;globalThis.preset=applySkillPreset;',context);
config.skills['42']={roles:[],training:true};
const beforeCard=JSON.stringify(config.skills['42']);
assert.ok(context.card(state.employees[0]).includes('Универсал'));
assert.equal(JSON.stringify(config.skills['42']),beforeCard,'rendering a card must not invent skills');
context.preset('42','universal');
assert.deepEqual(Array.from(config.skills['42'].roles),['kitchen','cashier']);
assert.equal(config.skills['42'].training,true,'quick presets preserve training status');
context.preset('42','kitchen');assert.deepEqual(Array.from(config.skills['42'].roles),['kitchen']);
context.preset('42','cashier');assert.deepEqual(Array.from(config.skills['42'].roles),['cashier']);
assert.throws(()=>context.preset('42','manager'),/Неизвестный/);
const preflight=source.slice(source.indexOf('  function generationProblems()'),source.indexOf('  function dayDate('));
vm.runInNewContext(preflight+';globalThis.problems=generationProblems;',context);
state.keeperPreview={};
assert.ok(context.problems().some(text=>text.includes('Файл ещё не применён')));
state.keeperPreview=null;config.forecasts.mon.revenue=null;
assert.ok(context.problems().some(text=>text.includes('прогноз выручки: ПН')));
config.forecasts.mon.revenue=10000;
assert.deepEqual(Array.from(context.problems()),[],'ready data must allow calculation');
config.reviewed=false;
assert.ok(context.problems().some(text=>text.includes('подтвердите часы')));
const generateButton=context.simple().match(/<button data-action="generate"[^>]*>/)[0];
assert.ok(!generateButton.includes('disabled'),'incomplete setup gives a visible explanation on click, not a dead button');
const outputs={plannerStatus:{classList:{toggle(){} }},plannerGenerateFeedback:{classList:{toggle(){} }}};
context.document={querySelector:id=>outputs[id.slice(1)]};
vm.runInNewContext(source.slice(source.indexOf('  function setStatus('),source.indexOf('  function generationProblems()'))+';globalThis.status=setStatus;',context);
context.status('Заполните выручку',true);
assert.equal(outputs.plannerGenerateFeedback.textContent,'Заполните выручку','failure is visible at the clicked button');
console.log('Planner understandable workflow tests passed');
