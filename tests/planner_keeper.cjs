const assert=require('node:assert/strict');
const K=require('../docs/control/planner-keeper.js');
const P=require('../docs/control/planner-engine.js');
const dates=['05','06','07','08','09','10','11'].map(day=>`${day}.10.2026`);
const td=(text,extra='')=>`<td ${extra}>${text}</td>`;
const row=values=>`<tr>${values.map(value=>td(value)).join('')}</tr>`;
function fixture(blank=false){
  const values=dates.flatMap((_,i)=>blank&&i===0?['&nbsp;','&nbsp;']:['2,00','40,00']);
  return `<html><table><tr>${dates.map(date=>td(date,'colspan="2"')).join('')}</tr>${row(['Час',...dates.flatMap(()=>['Чеков','Оплачено'])])}${row(['09',...values])}${row(['Итого',...dates.flatMap((_,i)=>blank&&i===0?['0,00','0,00']:['2,00','40,00'])])}</table></html>`;
}
const parsed=K.parse(fixture());
assert.equal(parsed.actuals.length,7);
assert.equal(parsed.daily[0].averageCheck,20);
assert.equal(parsed.dates[0],'2026-10-05');
assert.equal(K.decode(new TextEncoder().encode(fixture())).daily[0].checks,2);
const cp1251=Uint8Array.from([...fixture()].map(char=>{const n=char.codePointAt(0);return n>=0x410&&n<=0x44f?n-0x350:n;}));
assert.equal(K.decode(cp1251).daily[0].checks,2,'legacy Windows-1251 exports are decoded');
assert.throws(()=>K.parse(fixture().replace('40,00','41,00')),/не совпадает/);
assert.throws(()=>K.parse(fixture().replace('2,00','2,50')),/количество чеков/);
assert.throws(()=>K.parse(fixture().replace('06.10.2026','05.10.2026')),/семь дней/);
assert.throws(()=>K.parse(fixture().replace('Чеков','Гостей')),/порядок колонок/);
assert.throws(()=>K.parse(fixture().replace('09</td>','24</td>')),/некорректный час/);
assert.throws(()=>K.parse(fixture().replace('40,00','&nbsp;')),/одно из полей/);
assert.throws(()=>K.parse('not a workbook'),/выгрузка/);
const absent=K.parse(fixture(true));
assert.equal(absent.actuals.length,6);
assert.equal(absent.missing.length,1);
assert.equal(absent.daily[0].averageCheck,null);
const config=P.defaults();
P.DAYS.forEach(day=>{config.periods[day]={open:540,close:600,prep:0,cleanup:0};config.forecasts[day]={revenue:100,checks:5,averageCheck:10};});
const before=JSON.stringify(config),applied=K.apply(parsed,config,{profiles:true,averageChecks:true});
assert.equal(JSON.stringify(config),before,'apply must not mutate original inputs');
assert.equal(applied.forecasts.mon.revenue,100,'past sales never overwrite the revenue forecast');
assert.equal(applied.forecasts.mon.checks,null,'average-check mode explicitly replaces manual check forecast');
assert.equal(applied.forecasts.mon.averageCheck,20);
assert.equal(applied.profiles.mon[9],2);
assert.equal(applied.actuals.length,7);
assert.equal(K.apply(parsed,applied).actuals.length,7,'reimport is idempotent');
config.periods.mon.open=480;
assert.equal(K.missingTradingHours(parsed,config).length,1);
assert.throws(()=>K.apply(parsed,config,{profiles:true}),/пропуски/);
assert.doesNotThrow(()=>K.apply(parsed,config,{profiles:true,acknowledgeMissing:true}));
assert.equal(K.apply(parsed,config).forecasts.mon.checks,5,'history-only import preserves manual forecasts');
assert.throws(()=>K.apply(absent,config,{profiles:true,acknowledgeMissing:true}),/нет чеков/);
assert.deepEqual(K.apply(parsed,config).actuals,parsed.actuals,'history-only import does not synthesize missing observations');
console.log('r_keeper import tests passed');
